KEEP_EARLY = {"ASSET-015_bg"}   # 015 の背景は前日に作り、今日の指示「アセット15がないです」で渡した


def main():
    OUT.mkdir(exist_ok=True); (OUT / "見比べ用").mkdir(exist_ok=True); (OUT / "固定人物の基準画像").mkdir(exist_ok=True)
    rows = []
    mapping = {}
    for fix in ["Fix2", "Fix3", "Fix5a", "Fix5b", "Fix6"]:
        q, _, _ = mq.build(fix)
        for x in q:
            if x.get("deliver_as"):
                mapping.setdefault(x["id"], x["deliver_as"])
    for p in sorted((HERE / "images").glob("ASSET-*_overlay.png")):
        mapping[p.stem] = p.stem.replace("_overlay", "_bear") + ".png"
    copied = []
    for cut in sorted(ITEMS):
        ids = [i for i in mapping if i.startswith(f"ASSET-{cut}_")]
        files = []
        for i in sorted(ids):
            src = HERE / "images" / f"{i}.png"
            name = mapping[i]
            if not src.exists():
                files.append(f"{name}（未生成）"); continue
            if src.stat().st_mtime < 1790398800 and i not in KEEP_EARLY:   # 2026-09-26 14:00（本人の修正指示の開始）より前の画像は今回の修正分ではない
                continue
            shutil.copy2(src, OUT / name); copied.append(name)
            note = ""
            if i.endswith(("_char", "_overlay")):
                im = Image.open(src)
                if im.mode != "RGBA" or im.getextrema()[3][0] > 0:
                    note = "（透過なし）"
            before = OLD / name
            if before.exists():
                shutil.copy2(before, OUT / "見比べ用" / name.replace(".png", "_修正前.png"))
            files.append(name + note)
        if cut == "056" and (OLD / "ASSET-056_still.png").exists():   # 背景に使う。ドライブではゴミ箱に入っていたので手元の同じ画像を渡す
            shutil.copy2(OLD / "ASSET-056_still.png", OUT / "ASSET-056_still.png"); copied.append("ASSET-056_still.png"); files.append("ASSET-056_still.png（背景・元の画像）")
        for v in VID.glob(f"H3_{cut}.mp4"):
            shutil.copy2(v, OUT / f"ASSET-{cut}_video.mp4"); files.append(f"ASSET-{cut}_video.mp4"); copied.append(f"ASSET-{cut}_video.mp4")
        order, check, seen = ITEMS[cut]
        rows.append((cut, "・".join(files) or "（新しく作るものなし）", order, check, seen))
    # 今回の修正分でないファイル（前の実行の残り）はフォルダから外す
    for f in OUT.glob("*.*"):
        if f.suffix in (".png", ".mp4") and f.name not in copied:
            f.unlink()
    for c in sorted((HERE / "images").glob("CHAR-*.png")):
        shutil.copy2(c, OUT / "固定人物の基準画像" / c.name)
    lines = ["# せたな町 修正分チェックリスト（2026-09-26）", "",
             "ファイル名はドライブの今の名前と同じです。そのまま上書きしてください。修正前の画像は「見比べ用」にあります。", "",
             "| カット | 入っているファイル | 本人の指示 | 見る点 | Claude の目視 | 本人の確認 |", "|:--|:--|:--|:--|:--|:--|"]
    for cut, files, order, check, seen in rows:
        lines.append(f"| {cut} | {files} | {order} | {check} | {seen} | ☐ |")
    lines += ["", "## ドライブでの操作", "",
              "- ASSET-050_bg.png を ASSET-047_bg.png に名前を変える（047・050・153 が同じ会議室を使う。番号の若い素材の名前にそろえる）",
              "- ASSET-144_char.png の名前を ASSET-148_char.png に戻す必要はない（148 は新しいキャラで上書き。144 はキャラを使わない）",
              "- 動画16本は fal H3（768P・5秒）で作成。1本 $0.10、合計 約$1.60（約240円）",
              "- 使わなくなるファイル: ASSET-159_char.png・ASSET-162_bg.png・ASSET-166_char.png・ASSET-191_video.mp4・ASSET-217_char.png／_bg.png／_still.png など（編集者用ドキュメントの「使わない」に従う）", ""]
    (OUT / "チェックリスト.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(copied)}ファイル → {OUT}")

if __name__ == "__main__":
    main()
