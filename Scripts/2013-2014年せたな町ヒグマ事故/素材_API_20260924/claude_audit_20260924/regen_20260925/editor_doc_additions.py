REGEN_KIND = {"Lovart動画": "実写動画", "Lovart静止画": "静止画", "キャラアニメーション": "キャラアニメーション",
              "再利用": "流用", "Google Earth": "Google Earth（編集者が作成）"}
SPEAKER = {29: "女性", 129: "観光協会の職員", 177: "道の職員", 209: "男性"}
VIDEO_NOTE = {8: "動画は4.7秒（女性の顔が出る直前で切った）。足りなければ再生速度を落として尺いっぱいに使う。"}


def regen_sections(path: Path):
    """合格した Asset_Prompts_Regen.md から、ASSET番号→[セクション文字列]（165・177は前半・後半の2つ）を作る。"""
    text = path.read_text(encoding="utf-8")
    out = {}
    for chunk in text.split("\n---\n"):
        m = re.search(r"【制作メモ】ASSET-(\d+) \[([^\]]*)\]", chunk)
        if not m:
            continue
        no, kind = int(m.group(1)), m.group(2)
        narr = re.search(r"^ナレーター: (.*)$", chunk, re.M).group(1).strip()
        scene = re.search(r"^シーン: (.*)$", chunk, re.M).group(1).strip()
        labels, lines, in_code, label = [], [], False, ""
        for line in chunk.split("\n"):
            s = line.strip()
            if s.startswith("```"):
                if not in_code:
                    labels.append(label)
                in_code = not in_code
                continue
            if in_code:
                continue
            if s:
                label = s
            if not s or "プロンプト" in s or s.startswith(("ナレーター:", "【制作メモ】", "シーン:", "#")):
                continue
            lines.append(s)
        part = ""
        if no in (165, 177):
            part = "（前半）" if no not in out else "（後半）"
        files = []
        if kind == "Lovart動画":
            files = [f"ASSET-{no:03d}_video.mp4", f"ASSET-{no:03d}_still.png"]
        elif kind == "Lovart静止画":
            files = [f"ASSET-{no:03d}_still.png"]
        elif kind == "キャラアニメーション":
            if any("キャラプロンプト" in l for l in labels):
                files.append(f"ASSET-{no:03d}_char.png")
            if any("背景プロンプト" in l for l in labels):
                files.append(f"ASSET-{no:03d}_bg.png")
        sec = [f"## ASSET-{no:03d}{part}｜{REGEN_KIND.get(kind, kind)}（2026-09-25 作り直し）", ""]
        sec.append(f"- **ナレーション**: {narr}")
        sec.append(f"- **シーン**: {scene}")
        if files:
            sec.append("- **新しい素材**: " + "、".join(f"`{f}`" for f in files))
        key = f"{no}a" if part == "（前半）" and no == 165 else no
        has_serif = any(l.startswith(("→セリフ", "→職員セリフ")) for l in lines)
        for l in lines:
            if l.startswith("→ 編集者指示:"):
                sec.append(f"- **編集者指示**: {l.split(':', 1)[1].strip()}")
            elif re.match(r"→\S*セリフ", l):
                who, body = l[1:].split("「", 1)
                who = who.replace("セリフ", "").strip() or SPEAKER.get(no, "")
                if body.startswith("・・・") and no in SILENT_OVERRIDE:
                    sec.append(f"- **セリフ**: {SILENT_OVERRIDE[no]}")
                else:
                    sec.append(f"- **セリフ**: {who}「{body}")
            elif l.startswith("→アセット") or l.startswith("→ 背景は") or l.startswith("→ キャラは"):
                sec.append(f"- **流用**: {l.lstrip('→ ').strip()}")
            elif l.startswith("座標") or l.startswith("カメラ"):
                sec.append(f"- {l}")
        if not has_serif and key in REGEN_DIALOGUE:
            if no in SILENT_OVERRIDE and REGEN_DIALOGUE[key].endswith("「・・・」"):
                sec.append(f"- **セリフ**: {SILENT_OVERRIDE[no]}")
            else:
                who, body = REGEN_DIALOGUE[key].split("「", 1)
                sec.append(f"- **セリフ**: {who.replace('セリフ', '')}「{body}")
        if no in (165, 177):
            sec.append("- **注意**: ナレーションを2文に分ける案（台本の文言が変わるため本人確認待ち）。確定までは元の1文のまま、前半・後半の素材を順に使う。")
        if no in VIDEO_NOTE:
            sec.append(f"- **注意**: {VIDEO_NOTE[no]}")
        out.setdefault(no, []).append("\n".join(sec))
    return out


