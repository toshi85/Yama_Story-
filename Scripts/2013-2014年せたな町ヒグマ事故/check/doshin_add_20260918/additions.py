def add(anchor, groups, heading=None):
    global text
    lines = []
    if heading:
        lines += [heading, '']
    for source, sentences in groups:
        for i, sentence in enumerate(sentences.splitlines()):
            if i % 3 == 0:
                lines.append(f'<!-- src: 素材{source}。 -->')
            lines.append('ナレーター: ' + sentence)
        lines.append('')
    block = '\n'.join(lines) + '\n'
    assert text.count(anchor) == 1, anchor
    text = text.replace(anchor, block + anchor)
    blocks.append({'heading': heading, 'anchor': anchor, 'lines': lines})

